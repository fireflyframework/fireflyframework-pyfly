"""Tests for CLI: pyfly db commands."""

from __future__ import annotations

from pathlib import Path

import pytest
from click.testing import CliRunner

from pyfly.cli.main import cli


class TestDbInit:
    def test_db_init_creates_alembic_directory(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.chdir(tmp_path)
        runner = CliRunner()
        result = runner.invoke(cli, ["db", "init"])

        assert result.exit_code == 0, result.output
        assert (tmp_path / "alembic").is_dir()
        assert (tmp_path / "alembic.ini").is_file()
        assert (tmp_path / "alembic" / "env.py").is_file()

    def test_db_init_env_py_lists_the_models_and_the_framework_tables(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """C026/C027: target_metadata holds the application's models (the project's package, unless
        pyfly.data.relational.migrations.models lists others) and the framework's tables."""
        (tmp_path / "pyproject.toml").write_text('[project]\nname = "shop"\n')
        (tmp_path / "src" / "shop").mkdir(parents=True)
        (tmp_path / "src" / "shop" / "__init__.py").write_text("")
        monkeypatch.chdir(tmp_path)
        result = CliRunner().invoke(cli, ["db", "init"])
        assert result.exit_code == 0, result.output

        env_py = (tmp_path / "alembic" / "env.py").read_text()
        assert "MODEL_PACKAGES: list[str] = ['shop']" in env_py
        assert "target_metadata = migration_metadata(config, default_models=MODEL_PACKAGES)" in env_py
        assert "process_revision_directives=refuse_destructive_autogenerate" in env_py
        # WP05: autogenerated revisions import the module of PyFly's column types.
        assert "from pyfly.data.relational.sqlalchemy.types import render_item" in env_py
        assert env_py.count("render_item=render_item") == 2

    def test_db_init_outside_a_project_names_no_package(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.chdir(tmp_path)
        result = CliRunner().invoke(cli, ["db", "init"])
        assert result.exit_code == 0, result.output
        assert "MODEL_PACKAGES: list[str] = []" in (tmp_path / "alembic" / "env.py").read_text()
        assert "pyfly.data.relational.migrations.models" in result.output

    def test_db_init_env_py_runs_on_the_application_datasource(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.chdir(tmp_path)
        runner = CliRunner()
        runner.invoke(cli, ["db", "init"])

        env_py = (tmp_path / "alembic" / "env.py").read_text()
        assert "async with migration_connection(config) as connection:" in env_py
        assert 'config.attributes.get("connection")' in env_py  # the startup migrations hand one over
        assert "fileConfig(config.config_file_name, disable_existing_loggers=False)" in env_py
        compile(env_py, "env.py", "exec")


class TestDbMigrate:
    def test_db_migrate_requires_init_first(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.chdir(tmp_path)
